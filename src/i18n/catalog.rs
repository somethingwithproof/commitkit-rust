/// Look up the static message catalog for a locale.
pub const fn for_locale(locale: Locale) -> &'static Catalog {
    match locale {
        Locale::En => &EN,
        Locale::De => &DE,
        Locale::Es => &ES,
        Locale::Fr => &FR,
        Locale::It => &IT,
        Locale::PtBr => &PTBR,
        Locale::Nl => &NL,
        Locale::Ru => &RU,
        Locale::Uk => &UK,
        Locale::Ja => &JA,
        Locale::Ko => &KO,
        Locale::ZhCn => &ZHCN,
        Locale::ZhTw => &ZHTW,
        Locale::Ar => &AR,
        Locale::Hi => &HI,
        Locale::Pl => &PL,
        Locale::Tr => &TR,
        Locale::Sv => &SV,
        Locale::Vi => &VI,
        Locale::Id => &ID,
    }
}

